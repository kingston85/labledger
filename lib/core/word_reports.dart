const _bad = 'F8D7D7';
const _ctrl = 'DDF2E6';

String _std(Limit? l) {
  if (l == null) return 'NG';
  return l.unit.isEmpty ? l.text : l.text.replaceAll(' ${l.unit}', '');
}

String? _cf(double f) {
  if (f < 1) return null;
  if (f < 3) return 'FCF0C8';
  if (f < 6) return 'FBD9B0';
  return 'F6C9C9';
}

double _rsd(List<double> v) {
  final n = v.length;
  if (n < 2) return 0;
  final m = v.reduce((a, b) => a + b) / n;
  if (m == 0) return 0;
  final sd = math.sqrt(v.map((x) => (x - m) * (x - m)).reduce((a, b) => a + b) / (n - 1));
  return sd / m.abs() * 100;
}

class WordReports {
  WordReports._();

  static Uint8List investigation(AppState app, String project, List<Sample> samples) {
    final st = app.settings;
    final groups = buildInvestigation(samples, app.limitsFor);
    final d = DocxBuilder(
      landscape: true,
      title: 'Investigation report: $project',
      author: st.labName,
      footer: '${st.labName} · $project · generated by LabLedger ${shortDate(DateTime.now())}',
    );
    final dates = samples.map((s) => s.collectedAt).toList()..sort();
    final nResults = samples.fold<int>(0, (a, s) => a + s.results.length);
    var exceed = 0;
    for (final g in groups.where((g) => !g.solid)) {
      for (final s in g.samples) {
        for (final p in g.parameters) {
          final k = g.check(s, p).status;
          if (k == Compliance.exceed || k == Compliance.belowMin) exceed++;
        }
      }
    }

    d.titleBlock(project, kicker: st.labName, sub: 'Field investigation: laboratory results and assessment · issued ${shortDate(DateTime.now())}');
    d.table(
      ['Samples', 'Controls', 'Results', 'Non-compliant results', 'Sampling period'],
      [
        [
          '${samples.length}',
          '${samples.where((s) => s.isControl).length}',
          '$nResults',
          '$exceed',
          dates.isEmpty ? '—' : '${shortDate(dates.first)}${shortDate(dates.last) != shortDate(dates.first) ? ' – ${shortDate(dates.last)}' : ''}',
        ]
      ],
      size: 10,
      center: {0, 1, 2, 3, 4},
    );

    for (final g in groups) {
      d.heading('Key findings: ${g.title}');
      for (final l in allFindings(g)) {
        d.bullet(l);
      }
    }

    d.heading('Sampling locations');
    final reg = [...samples]..sort((a, b) => a.collectedAt.compareTo(b.collectedAt));
    d.table(
      ['Sample code', 'Location / description', 'Matrix', 'Lat, Lon', 'UTM 29N X', 'UTM 29N Y', 'Date', 'Time'],
      [
        for (final s in reg)
          () {
            final u = s.lat != null && s.lon != null ? toUtm(s.lat!, s.lon!, zone: 29) : null;
            return [
              '${s.code}${s.isControl ? ' (control)' : ''}',
              s.site,
              s.matrix.label,
              s.lat != null && s.lon != null ? '${s.lat!.toStringAsFixed(5)}, ${s.lon!.toStringAsFixed(5)}' : '—',
              u == null ? '—' : u.easting.toStringAsFixed(0),
              u == null ? '—' : u.northing.toStringAsFixed(0),
              shortDate(s.collectedAt),
              timeOfDay(s.collectedAt),
            ];
          }()
      ],
      widths: [1.4, 3.2, 1.2, 1.6, 0.9, 0.9, 1.1, 0.6],
      shade: (r, c) => reg[r].isControl ? _ctrl : null,
      boldCols: {0},
    );

    for (final g in groups) {
      const per = 8;
      for (var start = 0; start < g.samples.length; start += per) {
        final chunk = g.samples.sublist(start, math.min(start + per, g.samples.length));
        d.heading('Results: ${g.title}${g.samples.length > per ? ' (${start + 1}–${start + chunk.length})' : ''}', level: 2);
        d.table(
          ['Parameter', for (final s in chunk) s.isControl ? '${s.code} (control)' : s.code, if (!g.solid) 'Standard'],
          [
            for (final p in g.parameters) [paramHeader(g, p), for (final s in chunk) cellText(g.cell(s, p)), if (!g.solid) _std(g.limitFor(p))],
          ],
          widths: [2.6, for (final _ in chunk) 1.0, if (!g.solid) 1.1],
          center: {for (var i = 1; i <= chunk.length + 1; i++) i},
          shade: (r, c) {
            if (c == 0 || c > chunk.length) return null;
            final s = chunk[c - 1];
            final k = g.check(s, g.parameters[r]).status;
            if (!g.solid && (k == Compliance.exceed || k == Compliance.belowMin)) return _bad;
            return s.isControl ? _ctrl : null;
          },
        );
      }
      if (!g.solid && g.limits != null) d.note('Red cells: outside ${g.limits!.name}. NG = no guideline value. Green: control samples.');

      if (g.controls.isNotEmpty && g.impacted.isNotEmpty) {
        final imp = g.impacted;
        final params = g.parameters.where((p) => imp.any((s) => g.factor(s, p) != null)).toList();
        for (var start = 0; start < imp.length; start += 8) {
          final chunk = imp.sublist(start, math.min(start + 8, imp.length));
          d.heading(g.solid ? 'Contamination factor (CF = sample ÷ control): ${g.title}' : 'Enrichment versus control: ${g.title}', level: 2);
          d.table(
            ['Parameter', 'Control', for (final s in chunk) s.code],
            [
              for (final p in params)
                [
                  paramHeader(g, p),
                  () {
                    final ref = g.controlRef(p);
                    return ref == null ? '—' : '${ref.nonDetect ? '<' : ''}${fmtValue(ref.value)}';
                  }(),
                  for (final s in chunk) g.factor(s, p) == null ? '—' : g.factor(s, p)!.toStringAsFixed(g.factor(s, p)! >= 10 ? 0 : 1),
                ],
              if (g.solid) ['Pollution load index', '', for (final s in chunk) g.pli(s)?.toStringAsFixed(2) ?? '—'],
            ],
            widths: [2.6, 1.0, for (final _ in chunk) 1.0],
            center: {for (var i = 1; i <= chunk.length + 1; i++) i},
            shade: (r, c) {
              if (c < 2 || r >= params.length) return null;
              final f = g.factor(chunk[c - 2], params[r]);
              return f == null ? null : _cf(f);
            },
          );
        }
        d.note('Classes (Håkanson 1980): <1 low, 1–3 moderate, 3–6 considerable, ≥6 very high. A control below detection uses its detection limit.');
      }

      // Indices.
      final idx = computeIndices(g);
      String f(Indexed? x) => x == null ? '—' : '${x.value.toStringAsFixed(x.value.abs() >= 100 ? 0 : 1)} (${x.cls})';
      if (!g.solid && idx.any((e) => e.wqi != null || e.hpi != null)) {
        d.heading('Pollution indices: ${g.title}', level: 2);
        d.table(
          ['Sample', 'WQI', 'HPI', 'HEI', 'Contamination index', 'Nemerow index'],
          [for (final e in idx) [e.sample.isControl ? '${e.sample.code} (control)' : e.sample.code, f(e.wqi), f(e.hpi), f(e.hei), f(e.cd), f(e.nemerow)]],
          widths: [1.4, 1.6, 1.5, 1.2, 1.4, 1.5],
          shade: (r, c) => c > 0 && [idx[r].wqi, idx[r].hpi, idx[r].hei, idx[r].cd, idx[r].nemerow][c - 1]?.severity == 4 ? _bad : null,
        );
        d.note('WQI weighted arithmetic (≤25 excellent … >100 unsuitable for drinking); HPI critical value 100; HEI <10 low, >20 high; '
            'contamination index <1 low, >3 high; Nemerow ≤0.7 clean … >3 heavy. Non-detects taken as half the detection limit.');
      } else if (g.solid && g.controls.isNotEmpty) {
        final imp = idx.where((e) => !e.sample.isControl).toList();
        if (imp.isNotEmpty) {
          d.heading('Pollution indices: ${g.title}', level: 2);
          d.table(['Sample', 'Pollution load index', 'Degree of contamination', 'Ecological risk index (RI)'],
              [for (final e in imp) [e.sample.code, f(e.pli), f(e.cdeg), f(e.ri)]],
              widths: [1.4, 2, 2, 2]);
          final metals = g.parameters.where((p) => imp.any((e) => e.igeo.containsKey(p))).toList();
          for (var start = 0; start < imp.length; start += 8) {
            final chunk = imp.sublist(start, math.min(start + 8, imp.length));
            d.heading('Geo-accumulation index (Igeo): ${g.title}', level: 2);
            d.table(
              ['Parameter', for (final e in chunk) e.sample.code],
              [for (final p in metals) [p, for (final e in chunk) e.igeo[p] == null ? '—' : e.igeo[p]!.toStringAsFixed(2)]],
              widths: [2.4, for (final _ in chunk) 1.0],
              center: {for (var i = 1; i <= chunk.length; i++) i},
              shade: (r, c) {
                if (c == 0) return null;
                final v = chunk[c - 1].igeo[metals[r]];
                return v == null ? null : _cf(v <= 0 ? 0.5 : (v <= 2 ? 2 : (v <= 3 ? 4 : 7)));
              },
            );
          }
          d.note('Background = control mean. Igeo = log2(Cn/1.5Bn): ≤0 unpolluted … >5 extreme. RI = Σ Tr·CF: <150 low, 150–300 moderate, 300–600 considerable, ≥600 very high.');
        }
      }
    }

    d.heading('Quality assurance / quality control');
    final withReps = samples.expand((s) => s.results).where((r) => r.replicates.length > 1).toList();
    if (withReps.isNotEmpty) {
      d.bullet('${withReps.length} of $nResults results are means of replicate analyses (largest RSD '
          '${withReps.map((r) => _rsd(r.replicates)).reduce(math.max).toStringAsFixed(1)}%; acceptance ≤ ${st.replicateRsdMax.toStringAsFixed(0)}%).');
    }
    if (samples.any((s) => s.isControl)) d.bullet('Control (background) samples were collected outside the impact pathway and analysed with the same methods.');
    final methods = samples.expand((s) => s.results).map((r) => r.method).where((m) => m.isNotEmpty).toSet();
    if (methods.isNotEmpty) d.bullet('Methods / instruments: ${methods.join(', ')}.');
    final params = samples.expand((s) => s.results).map((r) => paramKey(r.parameter)).toSet();
    final qcRel = app.qc.where((q) => params.contains(paramKey(q.parameter))).take(20).toList();
    if (qcRel.isNotEmpty) {
      d.table(
        ['Check', 'Parameter', 'Batch', 'Date', 'Result', 'Status'],
        [
          for (final q in qcRel)
            () {
              final e = app.qcEvaluate(q);
              return [q.type.label, q.parameter, q.batch, shortDate(q.date), e.$3, e.$1 ? 'Pass' : 'FAIL'];
            }()
        ],
        widths: [1.5, 1.6, 1, 1, 3, 0.8],
      );
    }
    d.signatures([('Prepared by', st.analyst), ('Reviewed / approved by', st.reviewer), ('Date', '')]);
    return d.bytes();
  }

  /// One section per sample, like the PDF laboratory test report.
  static Uint8List samples(AppState app, List<Sample> samples) {
    final st = app.settings;
    final d = DocxBuilder(title: 'Laboratory test report', author: st.labName, footer: '${st.labName} · Results relate only to the samples as received.');
    for (var i = 0; i < samples.length; i++) {
      final s = samples[i];
      if (i > 0) d.pageBreak();
      final set = app.limitsFor(s);
      final checks = [for (final r in s.results) checkResult(r, set)];
      final bad = checks.where((c) => c.status == Compliance.exceed || c.status == Compliance.belowMin).length;
      d.titleBlock('Laboratory test report · ${s.code}', kicker: st.labName, sub: 'Issued ${shortDate(DateTime.now())}');
      if (app.needsApproval(s)) d.para('DRAFT: results not yet approved by a reviewer.', bold: true, color: 'C62828');
      final u = s.lat != null && s.lon != null ? toUtm(s.lat!, s.lon!, zone: 29) : null;
      d.table(
        ['Item', 'Details', 'Item', 'Details'],
        [
          ['Sample site', s.site, 'Collected', dateTime(s.collectedAt)],
          ['Project', s.project, 'Received', s.receivedAt == null ? '—' : dateTime(s.receivedAt!)],
          ['Matrix', '${s.matrix.label}${s.isControl ? ' (control)' : ''}', 'Collected by', s.collector],
          [
            'Coordinates',
            s.lat == null || s.lon == null ? '—' : '${s.lat!.toStringAsFixed(5)}, ${s.lon!.toStringAsFixed(5)}${u == null ? '' : '\nUTM ${u.toString()}'}',
            'Preservation',
            s.preservation,
          ],
        ],
        widths: [1.1, 2.4, 1.1, 2.4],
        boldCols: {0, 2},
        size: 9,
      );
      d.para(
        s.results.isEmpty
            ? 'No results recorded yet.'
            : bad > 0
                ? '$bad of ${s.results.length} parameters do not comply with ${set?.name ?? 'the selected limits'}.'
                : 'All ${s.results.length} parameters comply with ${set?.name ?? 'the selected limits'} (where a limit applies).',
        bold: true,
        color: bad > 0 ? 'C62828' : '0F8A55',
      );
      if (s.results.isNotEmpty) {
        d.heading('Results', level: 2);
        d.table(
          ['Parameter', 'Result', 'Unit', 'Method', 'Limit', 'Assessment'],
          [
            for (var k = 0; k < s.results.length; k++)
              [
                s.results[k].parameter,
                resultText(s.results[k]),
                s.results[k].unit,
                [s.results[k].method, if (s.results[k].replicates.length > 1) 'mean of n=${s.results[k].replicates.length}'].where((x) => x.isNotEmpty).join(', '),
                checks[k].limit?.text ?? '—',
                complianceLabel(checks[k].status),
              ]
          ],
          widths: [2.2, 1, 0.8, 2, 1.3, 1.2],
          center: {1, 2},
          shade: (r, c) => checks[r].status == Compliance.exceed || checks[r].status == Compliance.belowMin ? _bad : null,
        );
        for (final r in s.results.where((r) => r.note.isNotEmpty)) {
          d.note('${r.parameter}: ${r.note}');
        }
      }
      if (s.custody.isNotEmpty) {
        d.heading('Chain of custody', level: 2);
        d.table(['Date / time', 'Released by', 'Received by', 'Condition'], [for (final c in s.custody) [dateTime(c.time), c.from, c.to, c.condition]],
            widths: [1.4, 1.6, 1.6, 2.2]);
      }
      if (s.notes.isNotEmpty) d.para('Remarks: ${s.notes}');
      final appr = s.results.where((r) => r.approved).map((r) => r.approvedBy).toSet().join(', ');
      d.signatures([('Analysed by', s.results.map((r) => r.enteredBy).where((x) => x.isNotEmpty).toSet().join(', ').isEmpty ? st.analyst : s.results.map((r) => r.enteredBy).where((x) => x.isNotEmpty).toSet().join(', ')), ('Reviewed / approved by', appr.isEmpty ? st.reviewer : appr), ('Date', '')]);
    }
    return d.bytes();
  }
}
